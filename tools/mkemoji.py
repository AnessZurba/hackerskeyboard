#!/usr/bin/env python3
"""Builds app/src/main/assets/emoji.txt from Unicode's emoji-test.txt.

  curl -s -o emoji-test.txt https://unicode.org/Public/emoji/16.0/emoji-test.txt
  python3 tools/mkemoji.py emoji-test.txt app/src/main/assets/emoji.txt

Output: one line per group, "group<TAB>emoji emoji ...", fully-qualified emoji only,
without skin-tone variants and without the Component group.
Unicode data is under the Unicode License v3 (https://www.unicode.org/license.txt).
"""
import sys

SKIN_TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}


def main():
    src, dst = sys.argv[1], sys.argv[2]
    groups, current = [], None
    with open(src, encoding='utf-8') as f:
        for line in f:
            if line.startswith('# group:'):
                current = line.split(':', 1)[1].strip()
                groups.append((current, []))
                continue
            if not line.strip() or line.startswith('#') or current == 'Component':
                continue
            data, _, comment = line.partition('#')
            if '; fully-qualified' not in data:
                continue
            emoji = comment.split()[0]
            if any(c in SKIN_TONES for c in emoji):
                continue
            groups[-1][1].append(emoji)
    with open(dst, 'w', encoding='utf-8') as out:
        out.write('# Emoji by group, from Unicode emoji-test.txt (Unicode License v3). '
                  'Generated by tools/mkemoji.py.\n')
        for name, emoji in groups:
            if emoji:
                out.write(name + '\t' + ' '.join(emoji) + '\n')
    print(', '.join('%s: %d' % (n, len(e)) for n, e in groups if e))


if __name__ == '__main__':
    main()
