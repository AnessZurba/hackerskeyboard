#!/usr/bin/env python3
"""Builds app/src/main/assets/emoji.txt from Unicode's emoji-test.txt.

  curl -s -o emoji-test.txt https://unicode.org/Public/emoji/16.0/emoji-test.txt
  python3 tools/mkemoji.py emoji-test.txt app/src/main/assets/emoji.txt

Output: one line per group, "group<TAB>emoji emoji ...", fully-qualified emoji only,
without skin-tone variants and without the Component group; and emoji_tones.txt next
to it, "emoji<TAB>5 variants" for emoji that come in the five skin tones.
Unicode data is under the Unicode License v3 (https://www.unicode.org/license.txt).
"""
import sys

SKIN_TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}


def key(emoji):
    """An emoji without skin tones and variation selectors, to match variants to bases."""
    return ''.join(c for c in emoji if c not in SKIN_TONES and c != '\ufe0f')


def main():
    src, dst = sys.argv[1], sys.argv[2]
    tones_dst = dst.rsplit('/', 1)[0] + '/emoji_tones.txt' if '/' in dst else 'emoji_tones.txt'
    variants = {}  # key -> {tone: emoji}
    groups, current = [], None
    with open(src, encoding='utf-8') as f:
        for line in f:
            if line.startswith('# group:'):
                current = line.split(':', 1)[1].strip()
                groups.append((current, []))
                continue
            if not line.strip() or line.startswith('#') or current == 'Component':
                continue
            data, _, comment = line.partition('#')
            if '; fully-qualified' not in data:
                continue
            emoji = comment.split()[0]
            tones = {c for c in emoji if c in SKIN_TONES}
            if tones:
                if len(tones) == 1:  # one tone throughout (mixed-tone couples are skipped)
                    variants.setdefault(key(emoji), {})[tones.pop()] = emoji
                continue
            groups[-1][1].append(emoji)
    with open(dst, 'w', encoding='utf-8') as out:
        out.write('# Emoji by group, from Unicode emoji-test.txt (Unicode License v3). '
                  'Generated by tools/mkemoji.py.\n')
        for name, emoji in groups:
            if emoji:
                out.write(name + '\t' + ' '.join(emoji) + '\n')
    n = 0
    with open(tones_dst, 'w', encoding='utf-8') as out:
        out.write('# Skin-tone variants: emoji<TAB>light medium-light medium medium-dark dark. '
                  'Generated by tools/mkemoji.py.\n')
        for name, emoji in groups:
            for e in emoji:
                v = variants.get(key(e))
                if v and len(v) == 5:
                    out.write(e + '\t' + ' '.join(v[t] for t in sorted(v)) + '\n')
                    n += 1
    print(', '.join('%s: %d' % (n_, len(e)) for n_, e in groups if e), '| with tones:', n)


if __name__ == '__main__':
    main()
