#!/usr/bin/env python3
"""Builds app/src/main/assets/emoji_search.txt: search words for the emoji panel.

  for l in en ar he; do
    curl -sO https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotations/$l.xml
    curl -s -o ${l}_derived.xml https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotationsDerived/$l.xml
  done
  python3 tools/mkemojisearch.py <that dir> app/src/main/assets/emoji.txt app/src/main/assets/emoji_search.txt

Output: one line per emoji in emoji.txt, "emoji<TAB>name|keyword|keyword...", with the
English, Arabic and Hebrew names and keywords from CLDR, lower-cased, name first.
CLDR data is under the Unicode License v3 (https://www.unicode.org/license.txt).
"""
import sys
import xml.etree.ElementTree as ET

LANGS = ['en', 'ar', 'he']


def strip(e):
    return e.replace('️', '')


def load(path, words):
    for a in ET.parse(path).getroot().iter('annotation'):
        cp = strip(a.get('cp'))
        entry = words.setdefault(cp, ([], []))
        values = [v.strip().lower() for v in (a.text or '').split('|') if v.strip()]
        (entry[0] if a.get('type') == 'tts' else entry[1]).extend(values)


def main():
    src, emoji_txt, dst = sys.argv[1:4]
    words = {}
    for lang in LANGS:
        for name in (lang + '.xml', lang + '_derived.xml'):
            load(src + '/' + name, words)
    n = 0
    with open(emoji_txt, encoding='utf-8') as f, open(dst, 'w', encoding='utf-8') as out:
        out.write('# Emoji search words (CLDR annotations, en/ar/he; Unicode License v3). '
                  'Generated by tools/mkemojisearch.py.\n')
        for line in f:
            if line.startswith('#') or '\t' not in line:
                continue
            for e in line.rstrip('\n').split('\t', 1)[1].split(' '):
                names, keywords = words.get(strip(e), ([], []))
                seen, items = set(), []
                for w in names + keywords:
                    if w not in seen:
                        seen.add(w)
                        items.append(w)
                if items:
                    out.write(e + '\t' + '|'.join(items) + '\n')
                    n += 1
    print(n, 'emoji with search words')


main()
